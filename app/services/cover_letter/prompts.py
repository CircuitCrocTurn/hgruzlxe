"""
Сборка системного промпта.

ВАЖНО про кеширование DeepSeek (Context Caching on Disk):
- Кеш матчится по ПРЕФИКСУ от 0-го токена. Любое отличие в начале
  запроса (даже один пробел или дата) ломает hit.
- Поэтому всё, что должно кешироваться (резюме, шаблон, инструкции),
  кладём в самое начало system-сообщения и НЕ меняем между запросами.
- Уникальные/изменяющиеся вещи (текущая вакансия) идут в user-сообщении.
- Для одного и того же пользователя system-сообщение одно и то же
  во всех его диалогах → DeepSeek пометит этот префикс как cache prefix
  unit и будет переиспользовать его во всех будущих запросах.
"""

from __future__ import annotations

from textwrap import dedent


SYSTEM_PROMPT_TEMPLATE = dedent(
    """\
    # Шаблон сопроводительного письма

    Стиль: дружелюбный, по делу, без канцелярита. Длина: 150–220 слов.
    Язык: русский. Без markdown, только обычный текст с переводами строк.

    Структура:

    1. **Приветствие** (1 строка). Обращение по компании/команде, если она
      указана в вакансии. Если нет — нейтральное "Здравствуйте!".

    2. **Зацепка** (1–2 предложения). Почему именно эта вакансия / компания
      откликается. Если в вакансии есть конкретный продукт/проблема —
      упомяни её своими словами.
    3. **Релевантный опыт** (3–5 предложений). Подбери из резюме 2–3 факта,
      которые лучше всего матчатся на требования вакансии. Никаких выдумок:
      только то, что реально есть в резюме. Цифры и результаты — приветствуются.
    4. **Стек и совпадения** (1–2 предложения). Перечисли пересечения по
      технологиям из резюме и вакансии.

    5. **Закрытие** (1–2 предложения). Предложи следующий шаг (созвон,
      тестовое, ответы на вопросы). Без «жду вашего ответа с нетерпением».

    6. **Подпись**: имя кандидата из резюме и контакт (telegram или email
      из резюме). Без должности.
    """
)


SYSTEM_PROMPT_INSTRUCTIONS = dedent(
    """\
    Ты — ассистент по составлению сопроводительных писем.

    Тебе один раз выдают:
      1) РЕЗЮМЕ кандидата.
      2) ШАБЛОН сопроводительного письма (стиль, структура, тон).

    Дальше пользователь будет присылать ТЕКСТ ВАКАНСИИ. На каждое такое
    сообщение ты должен возвращать готовое сопроводительное письмо:
      - строго по шаблону (структура и тон);
      - опираясь только на факты из резюме (ничего не выдумывай);
      - подсвечивая релевантные навыки/опыт под конкретную вакансию;
      - на русском языке, если не указано иное.

    Формат ответа: только текст письма, без преамбул вида
    "Конечно, вот письмо:" и без markdown-обёрток.
    """
)


def build_system_prompt(resume: str) -> str:
    """Собирает стабильный system-prompt для кеширования.

    Структура и порядок секций фиксированы — менять их между запросами
    нельзя, иначе кеш не попадёт.
    """
    return (
        f"{SYSTEM_PROMPT_INSTRUCTIONS}\n"
        f"=== РЕЗЮМЕ КАНДИДАТА ===\n{resume.strip()}\n"
        f"=== ШАБЛОН СОПРОВОДИТЕЛЬНОГО ПИСЬМА ===\n{SYSTEM_PROMPT_TEMPLATE}\n"
        f"=== КОНЕЦ ИСХОДНЫХ ДАННЫХ ===\n"
    )


def build_user_prompt(vacancy_text: str) -> str:
    return (
        "Вакансия:\n"
        f"{vacancy_text.strip()}\n\n"
        "Сгенерируй сопроводительное письмо по шаблону."
    )
